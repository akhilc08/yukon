"""Export trained filters as a C header + JSON.   python export.py final_models.pkl OUT_DIR K [K ...]

C convention (y56_filter.h): ap[i] = a_p of the i-th prime (ap[0] = a_2, ap[1] = a_3, ...), 0 at bad primes.
Every scorer returns a float; larger = more likely high rank. Only compare scores within one family.
"""
from __future__ import annotations

import json
import math
import os
import pickle
import sys

import numpy as np

import data as D


def lin_c(name, w, b, K):
    W = [float(w[i]) / math.sqrt(D.PRIMES[i]) for i in range(K)]
    s = f"static const float {name}_W[{K}] = {{" + ",".join(f"{x:.7g}f" for x in W) + "};\n"
    s += (f"static inline float {name}(const int *ap) {{ float s = {float(b):.7g}f; "
          f"for (int i = 0; i < {K}; i++) s += {name}_W[i] * (float)ap[i]; return s; }}\n")
    return s, dict(kind="linear_ap", K=K, bias=float(b), w_ap=W)


def quad_c(name, w, b, K):
    W1 = [float(w[i]) / math.sqrt(D.PRIMES[i]) for i in range(K)]
    W2 = [float(w[K + i]) / D.PRIMES[i] for i in range(K)]
    s = f"static const float {name}_W1[{K}] = {{" + ",".join(f"{x:.7g}f" for x in W1) + "};\n"
    s += f"static const float {name}_W2[{K}] = {{" + ",".join(f"{x:.7g}f" for x in W2) + "};\n"
    s += (f"static inline float {name}(const int *ap) {{ float s = {float(b):.7g}f; "
          f"for (int i = 0; i < {K}; i++) {{ float a = (float)ap[i]; s += ({name}_W1[i] + {name}_W2[i] * a) * a; }} "
          f"return s; }}\n")
    return s, dict(kind="quad_ap", K=K, bias=float(b), w1_ap=W1, w2_ap=W2)


def gbm_c(name, booster, K):
    """Trees on x_i = a_i/sqrt(p_i); LightGBM sends x <= thr left. a integer: x <= thr <=> a <= floor(thr*sqrt p)."""
    dm = booster.dump_model()
    trees = []

    def node(n, depth):
        ind = "  " * depth
        if "leaf_value" in n:
            return f"{ind}s += {n['leaf_value']:.7g}f;\n"
        i = n["split_feature"]
        t = math.floor(n["threshold"] * math.sqrt(D.PRIMES[i]))  # thresholds are bin midpoints: no ties
        assert n["decision_type"] == "<="
        return (f"{ind}if (ap[{i}] <= {t}) {{\n" + node(n["left_child"], depth + 1) + f"{ind}}} else {{\n"
                + node(n["right_child"], depth + 1) + f"{ind}}}\n")

    body = "".join(node(t["tree_structure"], 1) for t in dm["tree_info"])
    s = f"static inline float {name}(const int *ap) {{\n  float s = 0.0f;\n{body}  return s;\n}}\n"
    return s, dict(kind="lgbm", K=K, model_str=booster.model_to_string())


def mlp_c(name, m, K):
    W1 = m.coefs_[0] / np.sqrt(np.array(D.PRIMES[:K]))[:, None]   # fold 1/sqrt(p) into first layer
    b1, W2, b2 = m.intercepts_[0], m.coefs_[1][:, 0], float(m.intercepts_[1][0])
    Hn = W1.shape[1]
    f = lambda v: ",".join(f"{x:.7g}f" for x in np.ravel(v))
    s = f"static const float {name}_W1[{K}][{Hn}] = {{" + ",".join("{" + f(r) + "}" for r in W1) + "};\n"
    s += f"static const float {name}_B1[{Hn}] = {{{f(b1)}}};\nstatic const float {name}_W2[{Hn}] = {{{f(W2)}}};\n"
    s += (f"static inline float {name}(const int *ap) {{ float h[{Hn}]; for (int j = 0; j < {Hn}; j++) h[j] = {name}_B1[j];\n"
          f"  for (int i = 0; i < {K}; i++) {{ float a = (float)ap[i]; if (a != 0.0f) for (int j = 0; j < {Hn}; j++) h[j] += {name}_W1[i][j] * a; }}\n"
          f"  float s = {b2:.7g}f; for (int j = 0; j < {Hn}; j++) s += {name}_W2[j] * (h[j] > 0.0f ? h[j] : 0.0f); return s; }}\n")
    return s, dict(kind="mlp_relu", K=K, W1_ap=W1.tolist(), b1=b1.tolist(), W2=W2.tolist(), b2=b2)


def main(pkl, out_dir, ks):
    final = pickle.load(open(pkl, "rb"))
    os.makedirs(out_dir, exist_ok=True)
    h = ["/* y56_filter.h -- learned rank filters (generated by y56/filter/export.py; see README.txt).",
         " * ap[i] = a_p of the i-th prime (2,3,5,...), set 0 at bad primes. Larger score = likelier high rank.",
         " * Compare scores only within one family (no per-family calibration). Baseline for reference:",
         " * y56_S(ap,K) = sum_{i>=1,i<K} -ap[i]*log(p_i)/p_i  (S(p_K), the usual Mestre-Nagao sieve). */",
         "#ifndef Y56_FILTER_H", "#define Y56_FILTER_H", ""]
    h.append("static const unsigned short y56_P[168] = {" + ",".join(map(str, D.PRIMES)) + "};")
    h.append("static const float y56_LW[168] = {" + ",".join(f"{math.log(p)/p:.7g}f" for p in D.PRIMES) + "};")
    h.append("static inline float y56_S(const int *ap, int nprimes) { float s = 0.0f; for (int i = 1; i < nprimes; i++) "
             "s -= y56_LW[i] * (float)ap[i]; return s; }\n")
    js = {}
    for K in ks:
        ms = final[K]
        for nm, fn in (("lin", lambda n, m: lin_c(n, m.coef_, m.intercept_, K)),
                       ("quad", lambda n, m: quad_c(n, m.coef_, m.intercept_, K)),
                       ("gbm", lambda n, m: gbm_c(n, m.booster_, K)),
                       ("mlp", lambda n, m: mlp_c(n, m, K))):
            if nm in ms:
                c, j = fn(f"y56_{nm}{K}", ms[nm])
                h.append(c)
                js[f"{nm}{K}"] = j
    h.append("#endif")
    open(os.path.join(out_dir, "y56_filter.h"), "w").write("\n".join(h) + "\n")
    json.dump(js, open(os.path.join(out_dir, "models.json"), "w"))
    print("wrote", list(js))


if __name__ == "__main__":
    main(sys.argv[1], sys.argv[2], [int(k) for k in sys.argv[3:]])
